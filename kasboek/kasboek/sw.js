// Geldwijzer service worker: bewaart alleen de app-bestanden, zodat hij ook offline opent.
// Nieuwste versie eerst (netwerk), bij geen verbinding de bewaarde versie.
const CACHE = 'geldwijzer-v1';
const CORE = ['./', 'index.html', 'styles.css', 'app.js', 'parsers.js', 'analysis.js', 'sample.js', 'favicon.svg', 'manifest.webmanifest'];
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(CORE)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => caches.match(req).then((r) => r || caches.match('index.html'))));
});
